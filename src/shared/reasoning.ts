/**
 * 추론(reasoning) 예산 상한 — **정본은 여기 하나**다.
 *
 * ── 왜 이 파일이 없었나 (실측 결함) ─────────────────────────────────────────
 *
 * 추론 예산의 기본값이 **세 곳에 따로** 적혀 있었다:
 *
 *   `src/web/agent/think.ts`      DEFAULT_MAX_REASONING = 1024   (화면 상태 머신)
 *   `src/config/schema.ts`        default: 1024                 (설정 화면)
 *   `src/server/agentService.ts`  DEFAULT_THINK = { …1024 }      (서버 강제 전환)
 *
 * 하나를 올려도 나머지 둘은 그대로다. 그리고 `agentService.ts` 의 주석은
 * **"웹의 상태 머신과 값이 달라지면 안 된다"** 고 직접 적어놓고도
 * 같은 숫자를 세 번 손으로 썼다. 규칙이 "한 곳에 둔다" 인데 정본이 세 개였다.
 *
 * 그래서 이 파일을 만들고 세 곳을 모두 여기 물린다.
 *
 * ── 왜 1024 가 너무 작았나 (사용자 실측 사례) ──────────────────────────────
 *
 * 35B 모델로 실제 디버깅을 시키면 사고가 **1,027 토큰**을 넘기고 화면이
 * `Thinking 꺼짐 (예산 초과)` 로 죽었다. 1024 는 **짧은 질문에는** 충분한 값이지
 * 실제 작업에는 아니라 — 여기가 상한이었다.
 *
 * §5.3 의 방어(초과 시 도구 호출 강제)는 **유지한다.** 버리는 게 아니라
 * **작동하는 값**으로 바꾼다: 상한을 올린다.
 *
 * ── 토큰 추정은 **여기서 만들지 않는다** ────────────────────────────────────
 *
 * 언어별로 세는 추정기가 **이미 있다** — `estimateTextTokens`
 * (`src/compaction/compactor.ts`): 한글·한자·가나를 **글자당 1.5 토큰**으로,
 * 나머지를 **0.25 토큰**(4글자/토큰)으로 센다.
 *
 * 추론 예산이 예전에 쓰던 `길이 / 3.4` 은 **영문만** 맞고 한글 사고의 실제 토큰을
 * **절반밖에 못 셌다.** 그래서 화면에 "1,027 토큰" 이 떠도 실제로는 그 두 배를 쓴
 * 셈이고, **표시된 숫자가 거짓말**이 된다.
 *
 * 여기서 **같은 계산을 또 쓰면 세 번째 복제**가 된다 — 위에서 없앤 것이 그 꼴이므로.
 * 그래서 추정은 `estimateTextTokens` 하나만 쓰고, 예산 상한만 이 파일이 소유한다.
 */

/**
 * 추론 예산 기본 상한.
 *
 * 예전 1,024 → 현재 4,096. 근거는 위의 실측 사례(1,027에서 잘림)와, 35B 모델이
 * 실제 작업에서 필요한 분량이다.
 *
 * **여전히 유한**하다. 무한 예산은 "생각만 하다가 아무것도 안 하는" 상태로 돌아간다
 * — §5.3 의 실측 근거(420토큰 사건)는 **방어해야 할 진짜 위험**이고, 그건
 * 상한을 **제거**하는 것으로 고치는 게 아니다.
 */
export const DEFAULT_MAX_REASONING = 4096;

/** 허용 상한 — 설정 스키마의 `max` 와 같아야 한다(두 벌이면 하나만 고쳐진다). */
export const MAX_REASONING_CEILING = 8192;

/** 허용 하한 — 설정 스키마의 `min`. */
export const MIN_REASONING_FLOOR = 64;

/**
 * 사용자가 준 값을 **여기로 좁힌다.** 규칙은 정본에 있고, **한 군데만** 좁힌다.
 *
 * 좁히는 곳이 셋(스키마 검증·에이전트 생성·웹 상태 머신)이면 셋이 서로 다르게
 * 해석한다. 그래서 여기 하나만 둔다 — 다른 곳은 이 함수를 부른다.
 *
 * **숫자가 아니면 기본값으로 돌린다.** 조용히 `NaN` 을 예산으로 삼으면 추론이
 * **영원히 안 끝나거나** 즉시 초과로 취급된다 — 잘못된 설정이 조용한 결함으로
 * 이어지지 않게 한다.
 */
export function clampReasoningBudget(value: unknown): number {
  // **`null`·`""`·`undefined` 를 0 으로 바꾸지 않는다.**
  //
  // `Number(null)` 은 **0** 이고 `Number("")` 도 0 이다. 그대로 좁히면 **최소값(64)**
  // 이 되어 사고가 거의 즉시 잘린다 — 설정 한 줄이 조용한 결함이 되는 가장 짧은 경로다.
  // "값이 없다" 는 "아무것도 하지 않는다" 로 읽어야 한다.
  if (value === null || value === undefined) return DEFAULT_MAX_REASONING;
  if (typeof value === "string" && value.trim() === "") return DEFAULT_MAX_REASONING;
  const n = typeof value === "number" ? value : Number(value);
  if (!Number.isFinite(n)) return DEFAULT_MAX_REASONING;
  return Math.max(MIN_REASONING_FLOOR, Math.min(MAX_REASONING_CEILING, Math.round(n)));
}